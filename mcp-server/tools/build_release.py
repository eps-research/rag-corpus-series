#!/usr/bin/env python3
"""Build the self-contained release of the Astro-RAG MCP Server.

    python tools/build_release.py                    # dist/astro-rag-mcp-server-<v>/ and .zip
    python tools/build_release.py --manifest-only    # just refresh MANIFEST.txt in the repo

The release directory contains the program files listed in MANIFEST.txt, the
five corpus files and fifteen FAISS artifacts under data/, data/SHA256SUMS
(checked by the server at every start), a top-level SHA256SUMS covering every
file, and RELEASE.json (version, git commit, file counts). The ZIP is
byte-reproducible: sorted entries, fixed timestamps, fixed permissions.

The same directory is the Docker build context for the Hugging Face Space,
so the ZIP, the Space and the Zenodo deposit are built from identical files.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

SERVER = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SERVER))

from astro_rag_mcp import __version__  # noqa: E402
from astro_rag_mcp.config import CORPORA, DataLayout, resolve_data_layout  # noqa: E402

TOP_FILES = [
    "launch.py", "README.md", "INSTALL.md", "TROUBLESHOOTING.md", "CHANGELOG.md",
    "LICENSE", "CORPUS_KEYS.md", "CITATION.cff", "RELEASING.md", "requirements-full.lock.txt", "Dockerfile", "requirements.txt",
    "requirements-semantic.txt", "requirements-dev.txt", "requirements.lock.txt", "MANIFEST.txt",
]
TREES = ["astro_rag_mcp", "tests", "clients", "tools"]
# Repository-root files bundled into the release root (referenced by the docs).
REPO_FILES = ["CORRECTIONS.md"]
LINK = re.compile(r"\]\(([^)\s]+)\)")


def broken_links(root: Path) -> list[str]:
    """Relative Markdown links under ``root`` that do not resolve inside ``root``."""
    bad = []
    for md in sorted(root.rglob("*.md")):
        if set(md.relative_to(root).parts) & SKIP_PARTS:
            continue
        for target in LINK.findall(md.read_text(encoding="utf-8")):
            if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
                continue
            path = (md.parent / target.split("#", 1)[0]).resolve()
            if not path.exists() or root.resolve() not in path.parents and path != root.resolve():
                bad.append(f"{md.relative_to(root)} -> {target}")
    return bad
SKIP_PARTS = {"__pycache__", ".pytest_cache", ".venv", "data", "dist"}
ZIP_DATE = (2026, 1, 1, 0, 0, 0)


def program_files() -> list[str]:
    files = [f for f in TOP_FILES if (SERVER / f).is_file() or f == "MANIFEST.txt"]
    for tree in TREES:
        for p in sorted((SERVER / tree).rglob("*")):
            rel = p.relative_to(SERVER)
            if p.is_file() and not (set(rel.parts) & SKIP_PARTS) and p.suffix not in (".pyc",):
                files.append(rel.as_posix())
    return sorted(set(files))


def write_manifest() -> list[str]:
    files = program_files()
    body = ("# Program files of the EPS Research Astro-RAG MCP Server (checked by launch.py).\n"
            "# Generated by tools/build_release.py; data files are checked via data/SHA256SUMS.\n"
            + "\n".join(files) + "\n")
    (SERVER / "MANIFEST.txt").write_text(body, encoding="utf-8", newline="\n")
    return files


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_commit() -> str:
    try:
        rev = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=SERVER, text=True).strip()
        dirty = subprocess.call(["git", "diff", "--quiet", "HEAD", "--", "."], cwd=SERVER) != 0
        return rev + ("+uncommitted-changes" if dirty else "")
    except Exception:
        return "unknown"


def index_states() -> dict[str, str]:
    from astro_rag_mcp.server import build_service
    svc = build_service()
    return {k: ci.state for k, ci in svc.semantic.indexes.items()}


def build(out_root: Path, allow_stale: bool = False) -> Path:
    states = index_states()
    stale = sorted(k for k, s in states.items() if s != "ok")
    if stale and not allow_stale:
        sys.exit(f"refusing to build a release: semantic indexes not current: {stale} ({states}). "
                 "Rebuild them (build_scripts/build_faiss_indexes.py), or pass --allow-stale "
                 "for a clearly labelled pre-release.")
    files = write_manifest()
    missing = [f for f in files if not (SERVER / f).is_file()]
    if missing:
        sys.exit(f"missing program files: {missing}")
    name = f"astro-rag-mcp-server-{__version__}" + ("-prerelease" if stale else "")
    stage = out_root / name
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)

    for f in files:
        dst = stage / f
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(SERVER / f, dst)

    repo_root = SERVER.parent
    for f in REPO_FILES:
        if not (repo_root / f).is_file():
            sys.exit(f"missing repository file {f}")
        shutil.copy2(repo_root / f, stage / f)
        files.append(f)

    src = resolve_data_layout()
    rel_out = DataLayout(stage / "data", "release")
    (stage / "data" / "corpora").mkdir(parents=True)
    (stage / "data" / "faiss").mkdir(parents=True)
    data_files = []
    for spec in CORPORA.values():
        shutil.copy2(src.corpus_path(spec), rel_out.corpus_path(spec))
        data_files.append(f"corpora/{spec.filename}")
        for suffix in (".faiss", "_ids.json", "_texts.json"):
            shutil.copy2(src.faiss_dir() / f"{spec.faiss_stem}{suffix}",
                         rel_out.faiss_dir() / f"{spec.faiss_stem}{suffix}")
            data_files.append(f"faiss/{spec.faiss_stem}{suffix}")
    manifest = src.faiss_dir() / "index_manifest.json"
    if manifest.is_file():
        shutil.copy2(manifest, rel_out.faiss_dir() / manifest.name)
        data_files.append(f"faiss/{manifest.name}")
    (stage / "data" / "SHA256SUMS").write_text(
        "".join(f"{sha256(stage / 'data' / f)}  {f}\n" for f in sorted(data_files)),
        encoding="utf-8", newline="\n")

    release = {
        "name": "EPS Research Astro-RAG MCP Server",
        "version": __version__,
        "git_commit": git_commit(),
        "program_files": len(files),
        "data_files": len(data_files),
        "corpora": {k: s.filename for k, s in CORPORA.items()},
        "embedding_model": "sentence-transformers/all-MiniLM-L6-v2",
        "mcp_transport": "Streamable HTTP at /mcp (JSON-RPC 2.0); stdio; no SSE endpoint",
        "semantic_index_states": states,
        "status": "release" if not stale else
                  f"PRE-RELEASE: semantic indexes not current for {stale}; not for publication",
    }
    bad = broken_links(stage)
    if bad:
        sys.exit("broken relative links in release documents:\n  " + "\n  ".join(bad))
    (stage / "RELEASE.json").write_text(json.dumps(release, indent=2) + "\n", encoding="utf-8")

    every = sorted(p.relative_to(stage).as_posix() for p in stage.rglob("*")
                   if p.is_file() and p.name != "SHA256SUMS" or p == stage / "data" / "SHA256SUMS")
    (stage / "SHA256SUMS").write_text(
        "".join(f"{sha256(stage / f)}  {f}\n" for f in every), encoding="utf-8", newline="\n")

    zpath = out_root / f"{name}.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(stage.rglob("*")):
            if p.is_file():
                zi = zipfile.ZipInfo(f"{name}/{p.relative_to(stage).as_posix()}", ZIP_DATE)
                zi.external_attr = (0o755 if p.suffix in (".py",) and p.parent == stage else 0o644) << 16
                zi.compress_type = zipfile.ZIP_DEFLATED
                z.writestr(zi, p.read_bytes())
    print(f"release dir : {stage}")
    print(f"release zip : {zpath}  sha256={sha256(zpath)}")
    print(f"files       : {len(files)} program + {len(data_files)} data")
    return zpath


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest-only", action="store_true")
    ap.add_argument("--out", default=str(SERVER / "dist"))
    ap.add_argument("--allow-stale", action="store_true",
                    help="build a '-prerelease' archive even if a semantic index is stale")
    a = ap.parse_args()
    if a.manifest_only:
        print(f"MANIFEST.txt: {len(write_manifest())} files")
        return
    build(Path(a.out), allow_stale=a.allow_stale)


if __name__ == "__main__":
    main()
